#!/usr/bin/env node
/**
 * scripts/generate-env.mjs
 * 
 * Genera src/environments/environment.generated.ts a partir de variables
 * de entorno (o archivo .env) para que Angular Esbuild las inyecte de forma
 * estática en el bundle de producción sin modificar environment.prod.ts en Git.
 */

import fs from 'fs';
import path from 'path';

const rootDir = process.cwd();
const envFilePath = path.join(rootDir, '.env');
const targetFile = path.join(rootDir, 'src', 'environments', 'environment.generated.ts');

// 1. Cargar variables de .env si no existen en process.env
if (fs.existsSync(envFilePath)) {
  const envContent = fs.readFileSync(envFilePath, 'utf-8');
  for (const line of envContent.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      // Quitar comillas si las tiene
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      if (!process.env[key]) {
        process.env[key] = val;
      }
    }
  }
}

const turnstileSiteKey = process.env.TURNSTILE_SITE_KEY || '';
const trialEnabled = process.env.TRIAL_ENABLED === 'true';

// 2. Fail-fast: Si TURNSTILE_SITE_KEY está ausente, abortar compilación
if (!turnstileSiteKey) {
  console.error('\x1b[31m[generate-env] ERROR CRÍTICO: TURNSTILE_SITE_KEY no está definido en process.env ni en .env.\x1b[0m');
  console.error('\x1b[33mPara compilar producción debe configurarse TURNSTILE_SITE_KEY (ej: 0x4AAAAAAA...).\x1b[0m');
  process.exit(1);
}

// 3. Generar archivo src/environments/environment.generated.ts
const fileContent = `/**
 * Auto-generated by scripts/generate-env.mjs at build time.
 * DO NOT EDIT MANUALLY - DO NOT COMMIT TO GIT
 */
export const generatedEnv = {
  turnstileSiteKey: ${JSON.stringify(turnstileSiteKey)},
  trialEnabled: ${trialEnabled},
};
`;

fs.writeFileSync(targetFile, fileContent, 'utf-8');
console.log(`\x1b[32m[generate-env] Archivo generado exitosamente:\x1b[0m ${targetFile}`);
console.log(`  - turnstileSiteKey: ${turnstileSiteKey.slice(0, 10)}...`);
console.log(`  - trialEnabled: ${trialEnabled}`);
